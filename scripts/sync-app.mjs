import { info } from 'node:console';
import process from 'node:process';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_STROKE = 3;

function objectBody(source, name) {
  const match = source.match(new RegExp(`const ${name}[^=]*=\\s*\\{([\\s\\S]*?)\\}`));
  if (!match) throw new Error(`Could not find "${name}" in the app source`);
  return match[1];
}

function entries(body) {
  return [...body.matchAll(/(\w+)\s*:\s*("[^"]+"|[\w.]+)/g)].map(([, key, value]) => [key, value]);
}

function resolveValue(value, colors) {
  if (value.startsWith('"')) return value.slice(1, -1);
  if (value.startsWith('colors.')) {
    const color = colors[value.slice('colors.'.length)];
    if (!color) throw new Error(`Unknown color reference ${value}`);
    return color;
  }
  return value;
}

export function parseTheme(themeSource) {
  const colors = Object.fromEntries(
    entries(objectBody(themeSource, 'colors')).map(([k, v]) => [k, resolveValue(v, {})]),
  );
  const moduleColor = Object.fromEntries(
    entries(objectBody(themeSource, 'moduleColor')).map(([k, v]) => [k, resolveValue(v, colors)]),
  );
  const radiusMatch = themeSource.match(/const radius\s*=\s*\{([^}]*)\}/);
  if (!radiusMatch) throw new Error('Could not find "radius" in the app theme');
  const radius = Object.fromEntries(entries(radiusMatch[1]).map(([k, v]) => [k, Number(v)]));
  const borderMatch = themeSource.match(/const border\s*=\s*(\d+)/);
  const border = borderMatch ? Number(borderMatch[1]) : 3;
  return { colors, moduleColor, radius, border };
}

export function parsePalette(drawingSource, colors) {
  return Object.fromEntries(
    entries(objectBody(drawingSource, 'PALETTE')).map(([k, v]) => [k, resolveValue(v, colors)]),
  );
}

function kebab(name) {
  return name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}

export function tokensCss({ colors, moduleColor, radius, border }) {
  const lines = [
    ...Object.entries(colors).map(([k, v]) => `  --color-${kebab(k)}: ${v};`),
    ...Object.entries(moduleColor).map(([k, v]) => `  --color-module-${k}: ${v};`),
    ...Object.entries(radius).map(([k, v]) => `  --radius-app-${k}: ${v}px;`),
    `  --border-app: ${border}px;`,
  ];
  return `/* Generated by scripts/sync-app.mjs from the Volcancito app. Do not edit. */\n@theme {\n${lines.join('\n')}\n}\n`;
}

export function normalizeShape(tuple) {
  const [kind, ...rest] = tuple;
  switch (kind) {
    case 'c': {
      const [cx, cy, r, fill, stroke] = rest;
      return { kind: 'circle', cx, cy, r, fill, stroke: stroke ?? DEFAULT_STROKE };
    }
    case 'o': {
      const [cx, cy, rx, ry, fill, stroke] = rest;
      return { kind: 'oval', cx, cy, rx, ry, fill, stroke: stroke ?? DEFAULT_STROKE };
    }
    case 'r': {
      const [x, y, w, h, r, fill, stroke] = rest;
      return { kind: 'rect', x, y, w, h, r, fill, stroke: stroke ?? DEFAULT_STROKE };
    }
    case 'p': {
      const [d, fill, stroke] = rest;
      return { kind: 'path', d, fill, stroke: stroke ?? DEFAULT_STROKE };
    }
    default:
      throw new Error(`Unknown art shape kind "${kind}"`);
  }
}

export function normalizeArt(art) {
  return Object.fromEntries(
    Object.entries(art).map(([id, shapes]) => [id, shapes.map(normalizeShape)]),
  );
}

function writeJson(path, data) {
  writeFileSync(path, `${JSON.stringify(data, null, 2)}\n`);
}

export function sync(appDir, outDir = ROOT) {
  const read = (path) => readFileSync(join(appDir, path), 'utf8');
  const generated = join(outDir, 'src/generated');
  mkdirSync(generated, { recursive: true });

  const theme = parseTheme(read('src/theme.ts'));
  writeFileSync(join(generated, 'tokens.css'), tokensCss(theme));
  writeJson(
    join(generated, 'palette.json'),
    parsePalette(read('src/components/drawing.tsx'), theme.colors),
  );

  writeJson(
    join(generated, 'art.json'),
    normalizeArt(JSON.parse(read('src/content/data/art.json'))),
  );
  for (const file of ['legal.json', 'vowels.json']) {
    copyFileSync(join(appDir, 'src/content/data', file), join(generated, file));
  }

  const fonts = join(outDir, 'src/assets/fonts');
  mkdirSync(fonts, { recursive: true });
  const fontFiles = [
    ['lexend', '400Regular', 'Lexend_400Regular'],
    ['lexend', '500Medium', 'Lexend_500Medium'],
    ['lexend', '600SemiBold', 'Lexend_600SemiBold'],
    ['lexend', '700Bold', 'Lexend_700Bold'],
    ['andika', '400Regular', 'Andika_400Regular'],
    ['andika', '700Bold', 'Andika_700Bold'],
  ];
  for (const [family, weight, file] of fontFiles) {
    copyFileSync(
      join(appDir, 'node_modules/@expo-google-fonts', family, weight, `${file}.ttf`),
      join(fonts, `${file}.ttf`),
    );
  }

  const publicDir = join(outDir, 'public');
  mkdirSync(publicDir, { recursive: true });
  copyFileSync(join(appDir, 'assets/images/favicon.png'), join(publicDir, 'favicon.png'));
  copyFileSync(join(appDir, 'assets/images/icon.png'), join(publicDir, 'apple-touch-icon.png'));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const appDir = resolve(process.env.VOLCANCITO_APP_DIR ?? join(ROOT, '../volcancito'));
  sync(appDir);
  info(`Synced design tokens and content from ${appDir}`);
}
